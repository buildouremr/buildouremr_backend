package com.ouremr.product.dto;

public class TeamListDTO {

    private Integer employeeProfileId;
    private String employeeFirstName;
    private String employeeLastName;
    private String employeeMiddleName;
    private String employeeMobileNo;
    private String employeeImage;
    private String employeeSpeciality;
    private String employeeRole;
    private Boolean employeeIsActive;

    public Integer getEmployeeProfileId() {
        return employeeProfileId;
    }

    public void setEmployeeProfileId(Integer employeeProfileId) {
        this.employeeProfileId = employeeProfileId;
    }

    public String getEmployeeFirstName() {
        return employeeFirstName;
    }

    public void setEmployeeFirstName(String employeeFirstName) {
        this.employeeFirstName = employeeFirstName;
    }

    public String getEmployeeLastName() {
        return employeeLastName;
    }

    public void setEmployeeLastName(String employeeLastName) {
        this.employeeLastName = employeeLastName;
    }

    public String getEmployeeMiddleName() {
        return employeeMiddleName;
    }

    public void setEmployeeMiddleName(String employeeMiddleName) {
        this.employeeMiddleName = employeeMiddleName;
    }

    public String getEmployeeMobileNo() {
        return employeeMobileNo;
    }

    public void setEmployeeMobileNo(String employeeMobileNo) {
        this.employeeMobileNo = employeeMobileNo;
    }

    public String getEmployeeImage() {
        return employeeImage;
    }

    public void setEmployeeImage(String employeeImage) {
        this.employeeImage = employeeImage;
    }

    public String getEmployeeSpeciality() {
        return employeeSpeciality;
    }

    public void setEmployeeSpeciality(String employeeSpeciality) {
        this.employeeSpeciality = employeeSpeciality;
    }

    public String getEmployeeRole() {
        return employeeRole;
    }

    public void setEmployeeRole(String employeeRole) {
        this.employeeRole = employeeRole;
    }

    public Boolean getEmployeeIsActive() {
        return employeeIsActive;
    }

    public void setEmployeeIsActive(Boolean employeeIsActive) {
        this.employeeIsActive = employeeIsActive;
    }
}
